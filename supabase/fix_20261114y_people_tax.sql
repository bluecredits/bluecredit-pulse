-- signed tax forms, insurance certificates, subcontracts and other paperwork for one onboarding record
create table if not exists public.onboarding_files (
  id bigint generated by default as identity primary key,
  workspace_id uuid not null default public.ws_default() references public.workspaces (id) on delete cascade,
  onboarding_id bigint not null references public.onboardings (id) on delete cascade,
  kind text not null default 'Other' check (kind in ('W-9', 'W-8BEN', 'W-8BEN-E', 'W-4', 'I-9', 'Insurance certificate', 'Agreement', 'ID or certification', 'Other')),
  name text not null, mime text, size int check (size is null or size <= 10485760), data_b64 text not null,
  uploaded_by uuid default auth.uid() references public.profiles (id) on delete set null,
  created_at timestamptz default now()
);
create index if not exists ix_onbf on public.onboarding_files (onboarding_id);
alter table public.onboarding_files enable row level security;
revoke all on public.onboarding_files from anon;
grant select, insert, delete on public.onboarding_files to authenticated;
create or replace function public.onb_mine(p_id bigint) returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from onboardings where id = p_id and workspace_id = ws() and user_id = auth.uid()) $$;
revoke execute on function public.onb_mine(bigint) from public, anon;
grant execute on function public.onb_mine(bigint) to authenticated;
drop policy if exists onbf_read on public.onboarding_files;
create policy onbf_read on public.onboarding_files for select to authenticated
  using (workspace_id = ws() and (staff_ws() is not null or onb_mine(onboarding_id)));
drop policy if exists onbf_insert on public.onboarding_files;
create policy onbf_insert on public.onboarding_files for insert to authenticated
  with check (workspace_id = ws() and uploaded_by = auth.uid()
    and exists (select 1 from onboardings o where o.id = onboarding_id and o.workspace_id = ws())
    and (staff_ws() is not null or onb_mine(onboarding_id)));
drop policy if exists onbf_delete on public.onboarding_files;
create policy onbf_delete on public.onboarding_files for delete to authenticated
  using (workspace_id = ws() and (is_admin() or uploaded_by = auth.uid()));
drop trigger if exists ws_write_guard on public.onboarding_files;
create trigger ws_write_guard before insert or update or delete on public.onboarding_files for each row execute function public.ws_write_guard();

-- a signed W-9 / W-8 / W-4 marks the tax form received and ticks the checklist's tax item
create or replace function public.onbf_tax_received() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  if new.kind in ('W-9', 'W-8BEN', 'W-8BEN-E', 'W-4') then
    update onboardings o set tax_form = new.kind, tax_status = 'Received', tax_received = current_date,
        us_person = case when new.kind in ('W-9', 'W-4') then true when new.kind like 'W-8%' then false else o.us_person end,
        checklist = coalesce((select jsonb_agg(case when i ->> 'id' = 'tax' and not coalesce((i ->> 'done')::boolean, false)
                    then i || jsonb_build_object('done', true, 'done_at', now(), 'done_by', coalesce((select display_name from profiles where id = auth.uid()), 'Pulse'))
                    else i end) from jsonb_array_elements(o.checklist) i), o.checklist)
      where o.id = new.onboarding_id;
  end if;
  return new;
end $$;
drop trigger if exists onbf_tax on public.onboarding_files;
create trigger onbf_tax after insert on public.onboarding_files for each row execute function public.onbf_tax_received();

