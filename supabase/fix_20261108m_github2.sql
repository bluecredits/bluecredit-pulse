-- a task's done date is the issue's closed date when GitHub gives one
create or replace function public.task_stamp() returns trigger language plpgsql as $$
begin
  new.updated_at := now();
  if new.status = 'Done' and (tg_op = 'INSERT' or old.status <> 'Done') then new.done_at := coalesce(new.done_at, now()); end if;
  if new.status <> 'Done' then new.done_at := null; end if;
  if new.assignee_id is not null and not exists (select 1 from profiles where id = new.assignee_id and workspace_id = new.workspace_id) then
    raise exception 'Assign tasks to someone on your own team.';
  end if;
  return new;
end $$;

-- GitHub stays the source of truth: people change those tasks and milestones in GitHub, the sync changes them here
create or replace function public.gh_guard() returns trigger language plpgsql as $$
declare o record := old;
begin
  if coalesce(current_setting('pulse.gh_sync', true), '') = 'on' or o.gh_number is null then return coalesce(new, old); end if;
  if tg_op = 'DELETE' then
    if exists (select 1 from gh_links where id = o.gh_link_id) and exists (select 1 from projects where id = o.project_id) then
      raise exception 'This comes from GitHub (% #%). Close or move it in GitHub, or unlink the repository in the project''s GitHub tab.', o.gh_repo, o.gh_number;
    end if;
    return old;
  end if;
  if tg_table_name = 'project_tasks' then
    if (new.title, new.status, new.assignee_id, new.milestone_id, new.gh_number, new.gh_repo) is distinct from (old.title, old.status, old.assignee_id, old.milestone_id, old.gh_number, old.gh_repo) then
      raise exception 'This task comes from GitHub (% #%). Change it in GitHub; Pulse picks it up within minutes.', o.gh_repo, o.gh_number;
    end if;
  elsif (new.name, new.due_date, new.done_at, new.gh_number) is distinct from (old.name, old.due_date, old.done_at, old.gh_number) then
    raise exception 'This milestone comes from GitHub (%). Change it in GitHub; Pulse picks it up within minutes.', o.gh_repo;
  end if;
  return new;
end $$;
drop trigger if exists gh_guard on public.project_tasks;
