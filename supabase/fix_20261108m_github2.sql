-- 2026-11-08m: GitHub refinements (re-runs the GitHub setup with them): tidier milestone and issue titles; a milestone counts as done when
-- every issue in it is closed (not only when GitHub closes the milestone); 'Doing' means labelled in progress or assigned and active in
-- the last 14 days (a shared account assigned to everything no longer makes every issue Doing); GitHub usernames can be given a name.
-- Then every linked repository re-syncs. Safe to run more than once.

-- 2026-11-08l: GitHub for Projects.
--   * A workspace connects GitHub in Admin → Integrations: the "Pulse for GitHub" app (one click, picks repos on GitHub,
--     instant updates through webhooks) or a read-only token an admin pastes (kept in Supabase Vault). A company whose repos sit
--     under several GitHub accounts or organizations connects each one; Pulse reads each repo through its owner's connection.
--   * Each project links one or more repositories, optionally narrowed to a GitHub milestone (e.g. "MVP", "Beta") or a label.
--     Issues become tasks and milestones become schedule milestones; GitHub stays the source of truth, so those tasks are
--     read-only in Pulse (status, title, assignee and milestone follow GitHub).
--   * Status: closed → Done; label "blocked" → Blocked; assigned or labelled in progress / review → Doing; else To do.
--     Priority from labels (urgent/critical/P0, high/P1, low/P3). Assignees match through People ↔ GitHub usernames.
--   * The database timer (pg_cron, every minute) asks GitHub through pg_net, the same way bid sources are read.
-- Safe to run more than once.

