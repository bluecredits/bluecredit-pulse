-- 1099-NEC summary for a calendar year (admins)
create or replace function public.tax_1099(p_year int) returns jsonb
language plpgsql stable security definer set search_path = public as $$
declare thr numeric := case when p_year >= 2026 then 2000 else 600 end;
begin
  if not is_admin() then raise exception 'Only admins can see the 1099 summary.'; end if;
  return jsonb_build_object('year', p_year, 'threshold', thr, 'rows', coalesce((
    select jsonb_agg(r order by r.paid desc, r.name) from (
      select o.id, o.name, o.entity, o.kind, o.firm, o.tax_form, o.tax_status, o.tax_class, o.us_person, o.status,
        coalesce(sum(c.amount), 0) as paid,
        (coalesce(o.us_person, o.tax_form is distinct from 'W-8BEN' and o.tax_form is distinct from 'W-8BEN-E')
          and coalesce(o.tax_class, '') !~* 'corporation|c corp|s corp'
          and coalesce(sum(c.amount), 0) >= thr) as needs_1099
      from onboardings o
      left join project_costs c on c.workspace_id = o.workspace_id and extract(year from c.cost_date) = p_year
        and (c.agreement_id in (select a.id from agreements a where a.onboarding_id = o.id)
             or (c.agreement_id is null and lower(trim(c.vendor)) in (lower(trim(o.name)), lower(trim(coalesce(o.firm, ''))))))
      where o.workspace_id = ws() and o.kind in ('Contractor', 'Consultant', 'Partner', 'Advisor', 'Intern')
      group by o.id) r
    where r.paid > 0 or r.status in ('Planned', 'In progress', 'Active')), '[]'));
end $$;
revoke execute on function public.tax_1099(int) from public, anon;
grant execute on function public.tax_1099(int) to authenticated;
