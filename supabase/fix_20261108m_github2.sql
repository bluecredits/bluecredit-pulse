-- which connection reads a path: the one for the repository's owner, else one that lists the repository, else the first
create or replace function public.gh_pick(p_ws uuid, p_path text) returns gh_conns
language plpgsql stable security definer set search_path = public as $$
declare c gh_conns; r text := substring(p_path from '^/repos/([^/]+/[^/?]+)');
begin
  select * into c from gh_conns g where g.workspace_id = p_ws
   order by (lower(g.account) = lower(split_part(coalesce(r, ''), '/', 1))) desc nulls last,
            exists (select 1 from jsonb_array_elements(g.repos) x where lower(x ->> 'full_name') = lower(r)) desc, g.id
   limit 1;
  if not found then raise exception 'GitHub isn''t connected. An admin connects it in Admin → Integrations.'; end if;
  return c;
end $$;
-- queue one GET to the GitHub API: directly with the connection's token, or through the Pulse for GitHub relay (app installs)
create or replace function public.gh_get(c gh_conns, p_path text) returns bigint
language plpgsql volatile security definer set search_path = public as $$
declare a gh_app; k text; rid bigint;
begin
  if c.method = 'token' then
    execute 'select decrypted_secret from vault.decrypted_secrets where id = $1' into k using c.token_secret_id;
    if k is null then raise exception 'The GitHub token is missing. Connect GitHub again in Admin → Integrations.'; end if;
    execute 'select net.http_get(url := $1, headers := $2, timeout_milliseconds := 60000)' into rid
      using 'https://api.github.com' || p_path, jsonb_build_object('Authorization', 'Bearer ' || k, 'Accept', 'application/vnd.github+json',
            'X-GitHub-Api-Version', '2022-11-28', 'User-Agent', 'Pulse-GitHub-Sync');
  else
    select * into a from gh_app where id = 1;
    if a.relay_url is null then raise exception 'The Pulse for GitHub app isn''t set up on this server.'; end if;
    execute 'select decrypted_secret from vault.decrypted_secrets where id = $1' into k using a.secret_id;
    execute 'select net.http_get(url := $1, params := $2, headers := $3, timeout_milliseconds := 60000)' into rid
      using a.relay_url, jsonb_build_object('installation', c.installation_id::text, 'path', p_path), jsonb_build_object('x-pulse-relay', coalesce(k, ''));
  end if;
  return rid;
end $$;
create or replace function public.gh_queue(p_ws uuid, p_link bigint, p_kind text, p_page int, p_path text, p_conn bigint default null) returns void
language plpgsql volatile security definer set search_path = public as $$
declare c gh_conns;
begin
  if p_conn is not null then select * into c from gh_conns where id = p_conn; else c := gh_pick(p_ws, p_path); end if;
  insert into gh_calls (workspace_id, link_id, conn_id, kind, page, request_id) values (p_ws, p_link, c.id, p_kind, p_page, gh_get(c, p_path));
end $$;
create or replace function public.gh_repos_path(c gh_conns) returns text language sql immutable as $$
  select case when c.method = 'app' then '/installation/repositories?per_page=100' else '/user/repos?per_page=100&sort=pushed' end $$;

create or replace function public.gh_issues_path(l gh_links, p_page int) returns text language sql stable as $$
  select '/repos/' || l.repo || '/issues?state=all&per_page=100&sort=updated&direction=asc&page=' || p_page
    || case when not l.sync_full and l.synced_until is not null
            then '&since=' || to_char((l.synced_until - interval '2 minutes') at time zone 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS"Z"') else '' end $$;

-- start a sync for one link: its milestones first, then its issues (only what changed since the last sync, unless full)
create or replace function public.gh_sync_link(p_link bigint, p_full boolean default false) returns void
language plpgsql volatile security definer set search_path = public as $$
declare l gh_links;
begin
  update gh_links set sync_started_at = now(), sync_full = p_full or synced_until is null, last_status = 'Syncing…' where id = p_link returning * into l;
  if not found then return; end if;
  begin
    perform gh_queue(l.workspace_id, l.id, 'milestones', 1, '/repos/' || l.repo || '/milestones?state=all&per_page=100&page=1');
    perform gh_queue(l.workspace_id, l.id, 'issues', 1, gh_issues_path(l, 1));
  exception when others then
    update gh_links set sync_started_at = null, last_error = case when sqlerrm ~* 'net\.|pg_net|http_get' then 'The database extension for fetching (pg_net) is not turned on.' else sqlerrm end,
           last_status = 'Couldn''t sync', next_sync_at = now() + interval '30 minutes' where id = p_link;
  end;
end $$;

-- store one page of milestones
create or replace function public.gh_store_milestones(l gh_links, p_body jsonb) returns int
language plpgsql volatile security definer set search_path = public as $$
declare m jsonb; n int := 0; many boolean;
begin
  perform set_config('pulse.gh_sync', 'on', true);
  many := (select count(distinct lower(repo)) from gh_links where project_id = l.project_id) > 1;
  for m in select * from jsonb_array_elements(case when jsonb_typeof(p_body) = 'array' then p_body else '[]' end) loop
    if l.milestone is not null and coalesce(m ->> 'title', '') not ilike '%' || l.milestone || '%' then continue; end if;
    insert into project_milestones (workspace_id, project_id, name, due_date, done_at, notes, sort, gh_link_id, gh_repo, gh_number, gh_url)
    values (l.workspace_id, l.project_id, left(btrim(regexp_replace(m ->> 'title', '\s+', ' ', 'g')), 200) || case when many then ' · ' || split_part(l.repo, '/', 2) else '' end,
            (m ->> 'due_on')::timestamptz::date, case when m ->> 'state' = 'closed' then coalesce((m ->> 'closed_at')::timestamptz::date, current_date) end,
            left(nullif(m ->> 'description', ''), 2000), (m ->> 'number')::int, l.id, l.repo, (m ->> 'number')::int, m ->> 'html_url')
    on conflict (project_id, lower(gh_repo), gh_number) where gh_number is not null do update
      set name = excluded.name, due_date = excluded.due_date, notes = excluded.notes, gh_url = excluded.gh_url;
    update project_milestones set gh_closed = case when m ->> 'state' = 'closed' then coalesce((m ->> 'closed_at')::timestamptz::date, current_date) end
     where project_id = l.project_id and lower(gh_repo) = lower(l.repo) and gh_number = (m ->> 'number')::int;
    n := n + 1;
  end loop;
  return n;
end $$;

-- store one page of issues as tasks (pull requests are skipped; issues that no longer fit the link's filter are removed)
create or replace function public.gh_store_issues(l gh_links, p_body jsonb) returns int
language plpgsql volatile security definer set search_path = public as $$
declare i jsonb; n int := 0; labs text[]; who text; st text; pri text; num int;
begin
  perform set_config('pulse.gh_sync', 'on', true);
  for i in select * from jsonb_array_elements(case when jsonb_typeof(p_body) = 'array' then p_body else '[]' end) loop
    if i ? 'pull_request' then continue; end if;
    num := (i ->> 'number')::int;
    labs := array(select lower(x ->> 'name') from jsonb_array_elements(coalesce(i -> 'labels', '[]')) x);
    if (l.milestone is not null and coalesce(i #>> '{milestone,title}', '') not ilike '%' || l.milestone || '%')
       or (l.label is not null and not (lower(l.label) = any (labs))) then
      delete from project_tasks where project_id = l.project_id and lower(gh_repo) = lower(l.repo) and gh_number = num and gh_link_id = l.id;
      continue;
    end if;
    who := coalesce(i #>> '{assignee,login}', i #>> '{assignees,0,login}');
    st := case when i ->> 'state' = 'closed' then 'Done'
               when exists (select 1 from unnest(labs) x where x ~ '^(status[: /-]*)?blocked$') then 'Blocked'
               when exists (select 1 from unnest(labs) x where x ~ '^(status[: /-]*)?(in[ -]?progress|doing|wip|in[ -]?review|review)$')
                 or (who is not null and (i ->> 'updated_at')::timestamptz > now() - interval '14 days') then 'Doing'
               else 'To do' end;
    pri := case when exists (select 1 from unnest(labs) x where x ~ '(urgent|critical|blocker|\mp0\M|priority[: /-]*(urgent|critical))') then 'Urgent'
                when exists (select 1 from unnest(labs) x where x ~ '(\mhigh\M|\mp1\M)') then 'High'
                when exists (select 1 from unnest(labs) x where x ~ '(\mlow\M|\mp3\M|\mp4\M)') then 'Low' else 'Normal' end;
    insert into project_tasks (workspace_id, project_id, milestone_id, title, description, status, priority, assignee_id, done_at, sort,
                               gh_link_id, gh_repo, gh_number, gh_url, gh_assignee, gh_labels)
    values (l.workspace_id, l.project_id,
            (select id from project_milestones where project_id = l.project_id and lower(gh_repo) = lower(l.repo) and gh_number = (i #>> '{milestone,number}')::int),
            left(btrim(regexp_replace(coalesce(nullif(i ->> 'title', ''), 'Issue #' || num), '\s+', ' ', 'g')), 300), left(nullif(i ->> 'body', ''), 4000), st, pri,
            (select user_id from gh_people where workspace_id = l.workspace_id and lower(login) = lower(who)),
            case when st = 'Done' then (i ->> 'closed_at')::timestamptz end, num, l.id, l.repo, num, i ->> 'html_url', who, labs)
    on conflict (project_id, lower(gh_repo), gh_number) where gh_number is not null do update
      set milestone_id = excluded.milestone_id, title = excluded.title, description = excluded.description, status = excluded.status,
          priority = excluded.priority, assignee_id = excluded.assignee_id, done_at = excluded.done_at, gh_url = excluded.gh_url,
          gh_assignee = excluded.gh_assignee, gh_labels = excluded.gh_labels;
    n := n + 1;
  end loop;
  return n;
end $$;

-- collect finished answers, store them, ask for the next page, and close finished syncs
create or replace function public.gh_collect(p_ws uuid) returns int
language plpgsql volatile security definer set search_path = public as $$
declare cl gh_calls; l gh_links; r record; body jsonb; got int; done int := 0; msg text;
begin
  for cl in select * from gh_calls where workspace_id = p_ws and status = 'pending' order by (kind = 'issues'), id loop
    select * into l from gh_links where id = cl.link_id;
    -- issues wait until the link's milestones are in, so tasks land on their milestone
    if cl.kind = 'issues' and exists (select 1 from gh_calls x where x.link_id = cl.link_id and x.kind = 'milestones' and x.status = 'pending') then continue; end if;
    begin
      execute 'select status_code, content, timed_out, error_msg from net._http_response where id = $1' into r using cl.request_id;
    exception when others then r := null; end;
    if r is null then
      if cl.created_at < now() - interval '10 minutes' then update gh_calls set status = 'error', error = 'GitHub didn''t answer', done_at = now() where id = cl.id; end if;
      continue;
    end if;
    body := null;
    begin body := r.content::jsonb; exception when others then body := null; end;
    if coalesce(r.status_code, 0) <> 200 or body is null then
      msg := case when r.timed_out then 'GitHub took too long to answer'
                  when r.status_code = 401 then 'GitHub refused the connection (the token was revoked or has expired). Connect GitHub again in Admin → Integrations.'
                  when r.status_code = 404 then 'Repository not found, or the GitHub connection can''t see it. Check the name and that it''s included in the token or app install.'
                  when r.status_code = 403 and coalesce(body ->> 'message', '') ilike '%rate limit%' then 'GitHub''s hourly limit was reached; trying again shortly.'
                  when r.status_code = 403 then 'GitHub said no: ' || coalesce(body ->> 'message', 'forbidden') || '. The token or app may need "Issues: read" permission.'
                  else 'GitHub answered ' || coalesce(r.status_code::text, 'nothing') || coalesce(': ' || (body ->> 'message'), coalesce(': ' || r.error_msg, '')) end;
      update gh_calls set status = 'error', http_status = r.status_code, error = msg, done_at = now() where id = cl.id;
      if cl.kind = 'repos' or r.status_code = 401 then update gh_conns set last_error = msg where id = cl.conn_id; end if;
      if l.id is not null then update gh_links set last_error = msg where id = l.id; end if;
      continue;
    end if;
    begin
      if cl.kind = 'repos' then
        update gh_conns set repos = (select coalesce(jsonb_agg(jsonb_build_object('full_name', x ->> 'full_name', 'private', (x ->> 'private')::boolean,
                   'description', x ->> 'description', 'pushed_at', x ->> 'pushed_at') order by x ->> 'pushed_at' desc nulls last), '[]')
                 from jsonb_array_elements(case when jsonb_typeof(body) = 'array' then body else coalesce(body -> 'repositories', '[]') end) x),
               account = coalesce(account, (select x #>> '{owner,login}' from jsonb_array_elements(case when jsonb_typeof(body) = 'array' then body else coalesce(body -> 'repositories', '[]') end) x
                                            group by 1 order by count(*) desc limit 1)),
               repos_at = now(), last_error = null where id = cl.conn_id;
        -- a new token for an account that already had one replaces the old one
        delete from gh_conns o using gh_conns n where n.id = cl.conn_id and o.workspace_id = n.workspace_id and o.id <> n.id
           and o.method = 'token' and n.method = 'token' and lower(o.account) = lower(n.account);
        got := 0;
      elsif l.id is null then got := 0;
      elsif cl.kind = 'milestones' then
        got := gh_store_milestones(l, body);
        if jsonb_array_length(body) = 100 then perform gh_queue(p_ws, l.id, 'milestones', cl.page + 1, '/repos/' || l.repo || '/milestones?state=all&per_page=100&page=' || (cl.page + 1)); end if;
      else
        got := gh_store_issues(l, body);
        if jsonb_array_length(body) = 100 then perform gh_queue(p_ws, l.id, 'issues', cl.page + 1, gh_issues_path(l, cl.page + 1)); end if;
      end if;
      update gh_calls set status = 'done', http_status = 200, done_at = now() where id = cl.id;
      done := done + 1;
    exception when others then
      update gh_calls set status = 'error', http_status = 200, error = 'Couldn''t store what GitHub sent: ' || sqlerrm, done_at = now() where id = cl.id;
      if l.id is not null then update gh_links set last_error = 'Couldn''t store what GitHub sent: ' || sqlerrm where id = l.id; end if;
    end;
  end loop;
  -- syncs with nothing left to wait for
  for l in select * from gh_links g where g.workspace_id = p_ws and g.sync_started_at is not null
            and not exists (select 1 from gh_calls x where x.link_id = g.id and x.status = 'pending') loop
    if exists (select 1 from gh_calls x where x.link_id = l.id and x.status = 'error' and x.created_at >= l.sync_started_at) then
      update gh_links set sync_started_at = null, last_sync_at = now(), next_sync_at = now() + interval '20 minutes',
             last_status = 'Couldn''t sync' where id = l.id;
    else
      perform set_config('pulse.gh_sync', 'on', true);
      update project_milestones m set done_at = coalesce(m.gh_closed,
               (select case when count(*) > 0 and bool_and(t.status = 'Done') then max(t.done_at)::date end from project_tasks t where t.milestone_id = m.id))
       where m.gh_link_id = l.id and m.done_at is distinct from coalesce(m.gh_closed,
               (select case when count(*) > 0 and bool_and(t.status = 'Done') then max(t.done_at)::date end from project_tasks t where t.milestone_id = m.id));
      update gh_links set sync_started_at = null, sync_full = false, synced_until = l.sync_started_at, last_sync_at = now(), last_error = null,
             next_sync_at = now() + make_interval(mins => coalesce((select every_min from gh_config where workspace_id = p_ws), 10)),
             issues = (select count(*) from project_tasks t where t.gh_link_id = l.id),
             last_status = 'Up to date' where id = l.id;
    end if;
  end loop;
  delete from gh_calls where workspace_id = p_ws and status <> 'pending' and created_at < now() - interval '2 days';
  return done;
end $$;

-- the timer: every minute, collect answers and start syncs that are due
create or replace function public.gh_tick() returns void
language plpgsql volatile security definer set search_path = public as $$
declare w uuid; lid bigint;
begin
  for w in select distinct workspace_id from gh_conns where ws_has_app_for(workspace_id, 'projects') loop
    begin
      perform gh_collect(w);
      for lid in select id from gh_links where workspace_id = w and active
                   and (next_sync_at is null or next_sync_at <= now())
                   and (sync_started_at is null or sync_started_at < now() - interval '15 minutes')
                   and exists (select 1 from projects p where p.id = gh_links.project_id and p.status <> 'Closed')
                 order by next_sync_at nulls first limit 20 loop
        perform gh_sync_link(lid);
      end loop;
    exception when others then
      insert into gh_config (workspace_id, last_error) values (w, 'Internal error: ' || sqlerrm) on conflict (workspace_id) do update set last_error = excluded.last_error;
    end;
  end loop;
end $$;

-- ---------------------------------------------------------------- called from the app
create or replace function public.gh_status() returns jsonb
language plpgsql stable security definer set search_path = public as $$
declare w uuid := staff_ws(); c gh_config; a gh_app;
begin
  if w is null then raise exception 'Only team members can see the GitHub connection.'; end if;
  select * into c from gh_config where workspace_id = w;
  select * into a from gh_app where id = 1;
  return jsonb_build_object('connected', exists (select 1 from gh_conns where workspace_id = w),
    'conns', (select coalesce(jsonb_agg(jsonb_build_object('id', g.id, 'method', g.method, 'account', g.account, 'token_hint', g.token_hint,
                'repos', jsonb_array_length(g.repos), 'repos_at', g.repos_at, 'last_error', g.last_error, 'connected_by', g.connected_by,
                'connected_at', g.connected_at) order by g.id), '[]') from gh_conns g where g.workspace_id = w),
    'repos', (select coalesce(jsonb_agg(x order by x ->> 'pushed_at' desc nulls last), '[]') from gh_conns g, jsonb_array_elements(g.repos) x where g.workspace_id = w),
    'every_min', coalesce(c.every_min, 10), 'last_error', coalesce(c.last_error, (select last_error from gh_conns where workspace_id = w and last_error is not null order by id limit 1)),
    'method', (select case when bool_and(method = 'app') then 'app' when bool_or(method = 'app') then 'mixed' else 'token' end from gh_conns where workspace_id = w),
    'app', a.slug is not null, 'app_slug', a.slug, 'links', (select count(*) from gh_links where workspace_id = w),
    'people', (select coalesce(jsonb_agg(jsonb_build_object('login', x.login, 'user_id', g.user_id, 'label', g.label) order by lower(x.login)), '[]')
                 from (select distinct on (lower(gh_assignee)) gh_assignee login from project_tasks where workspace_id = w and gh_assignee is not null
                       union select login from gh_people where workspace_id = w) x
                 left join gh_people g on g.workspace_id = w and lower(g.login) = lower(x.login)));
end $$;

create or replace function public.gh_set_token(p_token text, p_conn bigint default null) returns jsonb
language plpgsql volatile security definer set search_path = public as $$
declare w uuid := staff_ws(); c gh_conns; k text := trim(coalesce(p_token, '')); sid uuid;
begin
  perform plan_require('projects');
  if w is null or not is_admin() then raise exception 'Only admins can connect GitHub.'; end if;
  if k !~ '^(github_pat_[A-Za-z0-9_]{20,}|gh[pousr]_[A-Za-z0-9]{20,})$' then
    raise exception 'That doesn''t look like a GitHub token (they start with github_pat_ or ghp_).';
  end if;
  if p_conn is not null then
    select * into c from gh_conns where id = p_conn and workspace_id = w and method = 'token';
    if not found then raise exception 'That connection isn''t a token connection.'; end if;
  else
    insert into gh_conns (workspace_id, method, connected_by) values (w, 'token', member_name()) returning * into c;
  end if;
  begin
    if c.token_secret_id is null then
      execute 'delete from vault.secrets where name = $1' using 'pulse-github-token-' || c.id::text;   -- left over from an earlier connection
      execute 'select vault.create_secret($1, $2, $3)' into sid using k, 'pulse-github-token-' || c.id::text, 'GitHub token for a Pulse workspace (read issues)';
    else
      execute 'select vault.update_secret($1, $2)' using c.token_secret_id, k; sid := c.token_secret_id;
    end if;
  exception when undefined_function or invalid_schema_name then
    raise exception 'Supabase Vault isn''t turned on for this database (Database → Extensions → supabase_vault).';
  end;
  update gh_conns set token_secret_id = sid, token_hint = left(k, 11) || '…' || right(k, 4), last_error = null, connected_by = member_name(), connected_at = now()
   where id = c.id returning * into c;
  insert into gh_config (workspace_id) values (w) on conflict (workspace_id) do update set last_error = null;
  insert into activity (user_name, entity, action, summary) values (member_name(), 'team', 'update', 'Connected GitHub with a token');
  update gh_links set next_sync_at = null where workspace_id = w and last_error is not null;
  perform gh_queue(w, null, 'repos', 1, gh_repos_path(c), c.id);
  return gh_status();
end $$;

create or replace function public.gh_refresh_repos() returns jsonb
language plpgsql volatile security definer set search_path = public as $$
declare w uuid := staff_ws(); c gh_conns;
begin
  if w is null then raise exception 'Only team members can do this.'; end if;
  for c in select * from gh_conns where workspace_id = w loop perform gh_queue(w, null, 'repos', 1, gh_repos_path(c), c.id); end loop;
  if not found then raise exception 'Connect GitHub first.'; end if;
  return gh_status();
end $$;

create or replace function public.gh_disconnect(p_conn bigint default null) returns jsonb
language plpgsql volatile security definer set search_path = public as $$
declare w uuid := staff_ws(); c gh_conns;
begin
  if w is null or not is_admin() then raise exception 'Only admins can disconnect GitHub.'; end if;
  for c in select * from gh_conns where workspace_id = w and (p_conn is null or id = p_conn) loop
    if c.token_secret_id is not null then begin execute 'delete from vault.secrets where id = $1' using c.token_secret_id; exception when others then null; end; end if;
    delete from gh_conns where id = c.id;
    insert into activity (user_name, entity, action, summary) values (member_name(), 'team', 'update', 'Disconnected GitHub' || coalesce(' (' || c.account || ')', ''));
  end loop;
  return gh_status();
end $$;

create or replace function public.gh_set_every(p_min int) returns jsonb
language plpgsql volatile security definer set search_path = public as $$
begin
  if not is_admin() then raise exception 'Only admins can change this.'; end if;
  insert into gh_config (workspace_id, every_min) values (staff_ws(), greatest(2, least(1440, p_min)))
  on conflict (workspace_id) do update set every_min = excluded.every_min, updated_at = now();
  return gh_status();
end $$;

-- link a repository (optionally one milestone or label of it) to a project, and sync it straight away
create or replace function public.gh_link_add(p_project bigint, p_repo text, p_milestone text default null, p_label text default null) returns bigint
language plpgsql volatile security definer set search_path = public as $$
declare w uuid := staff_ws(); r text := trim(regexp_replace(coalesce(p_repo, ''), '^(https?://)?(www\.)?github\.com/|\.git$|/+$', '', 'gi')); lid bigint;
begin
  perform plan_require('projects');
  if not can_manage_project(p_project) then raise exception 'Only admins and the project''s manager can link GitHub.'; end if;
  if not exists (select 1 from gh_conns where workspace_id = w) then raise exception 'Connect GitHub first (Admin → Integrations).'; end if;
  r := split_part(r, '/', 1) || '/' || split_part(r, '/', 2);
  if r !~ '^[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+$' then raise exception 'Enter the repository as owner/name, e.g. bluecredits/bluecredit-pulse.'; end if;
  insert into gh_links (workspace_id, project_id, repo, milestone, label, created_by)
  values (w, p_project, r, nullif(trim(p_milestone), ''), nullif(trim(p_label), ''), member_name())
  on conflict (project_id, lower(repo), lower(coalesce(milestone, '')), lower(coalesce(label, ''))) do update set active = true
  returning id into lid;
  perform gh_sync_link(lid, true);
  -- the project's other repositories too: milestone names get the repository added once there's more than one
  perform gh_sync_link(id) from gh_links where project_id = p_project and id <> lid and active and sync_started_at is null;
  return lid;
end $$;

create or replace function public.gh_link_remove(p_link bigint) returns void
language plpgsql volatile security definer set search_path = public as $$
declare l gh_links;
begin
  select * into l from gh_links where id = p_link and workspace_id = staff_ws();
  if not found then raise exception 'Link not found.'; end if;
  if not can_manage_project(l.project_id) then raise exception 'Only admins and the project''s manager can unlink GitHub.'; end if;
  perform set_config('pulse.gh_sync', 'on', true);
  delete from gh_links where id = p_link;   -- its tasks and milestones go with it
end $$;

-- sync a project's links now (Sync now button, or right after linking); the page then calls gh_poll every few seconds
create or replace function public.gh_sync_project(p_project bigint, p_full boolean default false) returns void
language plpgsql volatile security definer set search_path = public as $$
declare lid bigint;
begin
  if not can_see_project(p_project) or staff_ws() is null then raise exception 'Project not found.'; end if;
  for lid in select id from gh_links where project_id = p_project and active and (sync_started_at is null or sync_started_at < now() - interval '2 minutes') loop
    perform gh_sync_link(lid, p_full);
  end loop;
end $$;
create or replace function public.gh_poll(p_project bigint default null) returns jsonb
language plpgsql volatile security definer set search_path = public as $$
declare w uuid := staff_ws();
begin
  if w is null then raise exception 'Only team members can sync GitHub.'; end if;
  perform gh_collect(w);
  return jsonb_build_object('pending', (select count(*) from gh_calls where workspace_id = w and status = 'pending'),
    'links', (select coalesce(jsonb_agg(to_jsonb(g) - 'workspace_id' order by g.id), '[]') from gh_links g where g.workspace_id = w and (p_project is null or g.project_id = p_project)),
    'repos_at', (select min(repos_at) from gh_conns where workspace_id = w), 'last_error', (select last_error from gh_conns where workspace_id = w and last_error is not null order by id desc limit 1));
end $$;

-- match a GitHub username to a person in Pulse; their issues are assigned to them from then on
create or replace function public.gh_map_person(p_login text, p_user uuid, p_label text default null) returns void
language plpgsql volatile security definer set search_path = public as $$
declare w uuid := staff_ws();
begin
  if w is null or not (is_admin() or exists (select 1 from projects where workspace_id = w and manager_id = auth.uid())) then
    raise exception 'Only admins and project managers can match GitHub people.';
  end if;
  if p_user is not null and not exists (select 1 from profiles where id = p_user and workspace_id = w) then raise exception 'That person isn''t on your team.'; end if;
  if p_user is null and nullif(trim(p_label), '') is null then delete from gh_people where workspace_id = w and lower(login) = lower(p_login);
  else insert into gh_people (workspace_id, login, user_id, label) values (w, trim(p_login), p_user, nullif(trim(p_label), ''))
       on conflict (workspace_id, login) do update set user_id = excluded.user_id, label = coalesce(excluded.label, case when excluded.user_id is null then gh_people.label end); end if;
  perform set_config('pulse.gh_sync', 'on', true);
  update project_tasks set assignee_id = p_user where workspace_id = w and lower(gh_assignee) = lower(p_login);
end $$;
drop function if exists public.gh_map_person(text, uuid);

-- ---------------------------------------------------------------- the Pulse for GitHub app
-- operator, once, after registering the app and deploying the github function (run in the SQL Editor):
--   select public.gh_app_setup('pulse-for-github', 'https://<project>.supabase.co/functions/v1/github', '<PULSE_RELAY_SECRET>');
create or replace function public.gh_app_setup(p_slug text, p_relay_url text, p_secret text) returns void
language plpgsql volatile security definer set search_path = public as $$
declare a gh_app; sid uuid;
begin
  if auth.uid() is not null and not is_operator() then raise exception 'Only Pulse operators can set up the GitHub app.'; end if;
  if length(coalesce(p_secret, '')) < 24 then raise exception 'Use a relay secret of at least 24 characters.'; end if;
  select * into a from gh_app where id = 1;
  if a.secret_id is null then
    execute 'delete from vault.secrets where name = $1' using 'pulse-github-relay';
    execute 'select vault.create_secret($1, $2, $3)' into sid using p_secret, 'pulse-github-relay', 'Shared secret between the database and the github function';
  else execute 'select vault.update_secret($1, $2)' using a.secret_id, p_secret; sid := a.secret_id; end if;
  insert into gh_app (id, slug, relay_url, secret_id) values (1, trim(p_slug), trim(p_relay_url), sid)
  on conflict (id) do update set slug = excluded.slug, relay_url = excluded.relay_url, secret_id = excluded.secret_id, updated_at = now();
end $$;
-- admin clicks Connect GitHub: a one-time code ties the install that comes back to this workspace
create or replace function public.gh_install_url() returns text
language plpgsql volatile security definer set search_path = public as $$
declare w uuid := staff_ws(); a gh_app; n text := pulse_token();
begin
  perform plan_require('projects');
  if w is null or not is_admin() then raise exception 'Only admins can connect GitHub.'; end if;
  select * into a from gh_app where id = 1;
  if a.slug is null then raise exception 'One-click GitHub isn''t available on this server yet. Use a token instead.'; end if;
  delete from gh_install_states where created_at < now() - interval '1 day';
  insert into gh_install_states (nonce, workspace_id, created_by) values (n, w, member_name());
  return 'https://github.com/apps/' || a.slug || '/installations/new?state=' || n;
end $$;
-- the github function (service role) after GitHub sends the admin back
create or replace function public.gh_app_connect(p_state text, p_installation bigint, p_account text) returns uuid
language plpgsql volatile security definer set search_path = public as $$
declare w uuid; who text; c gh_conns;
begin
  select workspace_id, created_by into w, who from gh_install_states where nonce = p_state and created_at > now() - interval '2 hours';
  if w is null then raise exception 'This GitHub connection link has expired. Click Connect GitHub again.'; end if;
  delete from gh_install_states where nonce = p_state;
  insert into gh_conns (workspace_id, method, installation_id, account, connected_by) values (w, 'app', p_installation, p_account, who)
  on conflict (installation_id) do update set workspace_id = excluded.workspace_id, account = excluded.account, last_error = null,
     connected_by = excluded.connected_by, connected_at = now()
  returning * into c;
  -- the app replaces a token for the same account
  delete from gh_conns where workspace_id = w and method = 'token' and lower(account) = lower(p_account);
  insert into gh_config (workspace_id) values (w) on conflict do nothing;
  insert into activity (workspace_id, user_name, entity, action, summary) values (w, 'GitHub', 'team', 'update', 'Connected GitHub (' || coalesce(p_account, 'app') || ')');
  update gh_links set next_sync_at = null where workspace_id = w;
  perform gh_queue(w, null, 'repos', 1, gh_repos_path(c), c.id);
  return w;
end $$;
-- the github function on a webhook: something changed in a repo, so sync the links that watch it now
create or replace function public.gh_app_event(p_installation bigint, p_repo text, p_event text) returns int
language plpgsql volatile security definer set search_path = public as $$
declare c gh_conns; lid bigint; n int := 0;
begin
  select * into c from gh_conns where installation_id = p_installation;
  if not found then return 0; end if;
  if p_event in ('installation.deleted', 'installation.suspend') then
    delete from gh_conns where id = c.id;
    insert into gh_config (workspace_id, last_error) values (c.workspace_id, 'The Pulse for GitHub app was removed from ' || coalesce(c.account, 'a GitHub account') || ' on GitHub. Connect again to keep syncing its repositories.')
    on conflict (workspace_id) do update set last_error = excluded.last_error;
    return 0;
  end if;
  if p_event like 'installation%' then perform gh_queue(c.workspace_id, null, 'repos', 1, gh_repos_path(c), c.id); return 0; end if;
  for lid in select id from gh_links where workspace_id = c.workspace_id and active and lower(repo) = lower(p_repo)
               and (sync_started_at is null or sync_started_at < now() - interval '15 minutes') loop
    perform gh_sync_link(lid);
    n := n + 1;
  end loop;
  return n;   -- the timer collects the answers within a minute
end $$;

