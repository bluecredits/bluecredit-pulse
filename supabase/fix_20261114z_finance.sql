-- ================================================================ fix z · Finance app (Nov 14 2026)
-- A finance app for admins, built on the SBDC financial-model layout (income statement and cash flow by month,
-- payroll and loan planners, balance sheet) and fed by what Pulse already records:
--   * revenue from invoices (Documents → Invoices), cash basis (when paid) or accrual (when sent)
--   * project costs (Projects), approved and reimbursed expense reports (Timecards → Expenses)
--   * transactions entered or imported in Finance (bills paid, owner investment, loans, history from a model)
-- Tables: fin_accounts (chart of accounts, each with its Form 1120 line), fin_entries (transactions),
--         fin_budget (plan by account and month), fin_map (which account each cost / expense category posts to).
-- fin_report(from, to, basis) returns accounts, actuals and budget by month; fin_projects(from, to) returns
-- project profitability. Settings (fiscal year start, basis, opening cash, payroll and loan planners) live in
-- workspaces.config.finance. Finance is admins only and part of the Pro plan.
-- Safe to run more than once.

create table if not exists public.fin_accounts (
  id bigint generated by default as identity primary key,
  workspace_id uuid not null default public.ws_default() references public.workspaces (id) on delete cascade,
  section text not null check (section in ('Revenue', 'Cost of revenue', 'Payroll', 'Professional services', 'Sales and marketing',
                                           'Operating expenses', 'Other income', 'Other expenses', 'Owner and financing')),
  grp text,                                         -- optional group within a section (e.g. Hourly, Fixed-fee)
  name text not null,
  driver text not null default 'amount' check (driver in ('amount', 'units', 'hours')),
  unit_price numeric,                               -- price per unit or hourly rate, for planning
  unit_cost numeric,                                -- direct cost per unit, for planning
  direction text not null default 'out' check (direction in ('in', 'out')),
  tax_line text,                                    -- Form 1120 line it rolls up to ('1a', '2', '26' ...); null = not on the return
  sort int not null default 0,
  active boolean not null default true,
  sys text,                                         -- built-in account key (rev_services, cor_other, misc ...)
  note text,
  created_at timestamptz default now(),
  unique (workspace_id, section, name)
);
create table if not exists public.fin_entries (
  id bigint generated by default as identity primary key,
  workspace_id uuid not null default public.ws_default() references public.workspaces (id) on delete cascade,
  entry_date date not null,
  account_id bigint not null references public.fin_accounts (id) on delete cascade,
  amount numeric(14, 2) not null,                   -- positive in the account's normal direction; negative for refunds
  payee text, memo text, ref text,
  project_id bigint references public.projects (id) on delete set null,
  batch text,                                       -- set for imported rows, so an import can be undone in one step
  created_by uuid default auth.uid() references public.profiles (id) on delete set null,
  created_at timestamptz default now()
);
create index if not exists ix_fin_entries on public.fin_entries (workspace_id, entry_date);
create table if not exists public.fin_budget (
  workspace_id uuid not null default public.ws_default() references public.workspaces (id) on delete cascade,
  account_id bigint not null references public.fin_accounts (id) on delete cascade,
  month date not null check (extract(day from month) = 1),
  qty numeric,                                      -- units or hours, when the account is planned that way
  amount numeric(14, 2) not null default 0,
  primary key (account_id, month)
);
create index if not exists ix_fin_budget on public.fin_budget (workspace_id, month);
create table if not exists public.fin_map (
  workspace_id uuid not null default public.ws_default() references public.workspaces (id) on delete cascade,
  source text not null check (source in ('invoice', 'cost', 'expense')),
  category text not null,
  account_id bigint not null references public.fin_accounts (id) on delete cascade,
  primary key (workspace_id, source, category)
);
alter table public.inv_invoices add column if not exists fin_account_id bigint references public.fin_accounts (id) on delete set null;

do $$ declare t text; begin
  foreach t in array array['fin_accounts', 'fin_entries', 'fin_budget', 'fin_map'] loop
    execute format('alter table public.%I enable row level security', t);
    execute format('revoke all on public.%I from anon', t);
    execute format('grant select, insert, update, delete on public.%I to authenticated', t);
    execute format('drop policy if exists fin_admin on public.%I', t);
    execute format('create policy fin_admin on public.%I for all to authenticated using (workspace_id = ws() and is_admin()) with check (workspace_id = ws() and is_admin())', t);
    execute format('drop policy if exists plan_gate on public.%I', t);
    execute format('create policy plan_gate on public.%I as restrictive for all to authenticated using (public.ws_has_app(%L)) with check (public.ws_has_app(%L))', t, 'finance', 'finance');
    execute format('drop trigger if exists ws_write_guard on public.%I', t);
    execute format('create trigger ws_write_guard before insert or update or delete on public.%I for each row execute function public.ws_write_guard()', t);
  end loop;
end $$;

-- Finance is a Pro app
create or replace function public.app_plan(p_app text) returns text language sql immutable as $$
  select case when p_app in ('opportunities', 'projects', 'agreements', 'hiring', 'invoices', 'finance') then 'pro'
              when p_app in ('chief', 'scheduler') then 'enterprise' else 'starter' end $$;

-- the starting chart of accounts (the SBDC model's lines, plus what Pulse records), created the first time Finance opens
create or replace function public.fin_setup() returns int
language plpgsql volatile security definer set search_path = public as $$
begin
  if not is_admin() then raise exception 'Only admins can use Finance.'; end if;
  perform plan_require('finance');
  return fin_setup_for(ws());
end $$;
