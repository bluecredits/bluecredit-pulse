-- * People → Team can onboard a company (a partner, prime or subcontractor such as AllGreen) as well as a person:
--   entity = 'Person' | 'Company', type adds 'Partner', and company details (UEI, CAGE, address, website, main contact).
-- * Tax forms: each record says which form is needed (W-9, W-8BEN, W-8BEN-E, W-4) and its status, plus the tax
--   classification from the form. The signed form itself is uploaded to the record's Documents (onboarding_files);
--   uploading a W-9 / W-8 marks the form received and ticks the "tax" checklist item. The person can upload their own
--   form from the employee portal. No tax ID numbers are stored in columns: only the signed file, staff and the person only.
-- * Projects get a pay floor (for example a Service Contract Act wage determination rate + health & welfare);
--   Pulse warns when someone's rate on the project is below it.
-- * tax_1099(year): what each contractor was paid in the year (project costs linked to their agreements or with their
--   name as vendor) and whether a 1099-NEC is due: US person, not a corporation, total at or over the threshold
--   ($600 for payments through 2025, $2,000 from 2026 under the 2025 tax law).
-- The default base rate for new people lives in workspaces.config.base_rate (set in People → Rates).
-- Safe to run more than once.

