-- invoice revenue (before sales tax) for one invoice
create or replace function public.fin_inv_net(i public.inv_invoices) returns numeric language sql immutable as $$
  select greatest(coalesce((select sum(coalesce((x ->> 'qty')::numeric, 0) * coalesce((x ->> 'rate')::numeric, 0)) from jsonb_array_elements(i.items) x), 0) - coalesce(i.discount, 0), 0) $$;
create or replace function public.fin_inv_total(i public.inv_invoices) returns numeric language sql immutable as $$
  select fin_inv_net(i) * (1 + coalesce(i.tax_rate, 0) / 100) $$;

-- accounts, actuals by account and month (and where they came from), and the budget, for a date range
create or replace function public.fin_report(p_from date, p_to date, p_basis text default 'cash') returns jsonb
language plpgsql stable security definer set search_path = public as $$
declare w uuid := ws(); cash boolean := coalesce(p_basis, 'cash') <> 'accrual';
  d_inv bigint; d_cost bigint; d_exp bigint;
begin
  if not is_admin() then raise exception 'Only admins can use Finance.'; end if;
  perform plan_require('finance');
  d_inv := coalesce((select account_id from fin_map where workspace_id = w and source = 'invoice' and category = '*'), (select id from fin_accounts where workspace_id = w and sys = 'rev_services'));
  d_cost := (select id from fin_accounts where workspace_id = w and sys = 'cor_other');
  d_exp := (select id from fin_accounts where workspace_id = w and sys = 'misc');
  return jsonb_build_object(
    'accounts', coalesce((select jsonb_agg(to_jsonb(a) order by a.sort, a.id) from fin_accounts a where a.workspace_id = w), '[]'),
    'actual', coalesce((select jsonb_agg(jsonb_build_object('a', x.a, 'm', x.m, 'src', x.src, 'v', round(x.v, 2), 'n', x.n)) from (
      select a, to_char(d, 'YYYY-MM') m, src, sum(v) v, count(*) n from (
        -- invoices
        select coalesce(i.fin_account_id, d_inv) a, case when cash then i.paid_at else i.issue_date end d, 'invoice' src,
               case when cash then case when fin_inv_total(i) > 0 then coalesce(i.paid_amount, fin_inv_total(i)) * fin_inv_net(i) / fin_inv_total(i) else 0 end else fin_inv_net(i) end v
          from inv_invoices i where i.workspace_id = w and (case when cash then i.status = 'Paid' else i.status in ('Sent', 'Paid') end)
        union all
        -- project costs entered in Projects (expense-report costs are counted from the reports below)
        select coalesce(m.account_id, d_cost), c.cost_date, 'cost', c.amount
          from project_costs c left join fin_map m on m.workspace_id = w and m.source = 'cost' and m.category = c.category
         where c.workspace_id = w and c.expense_item_id is null
        union all
        -- expense reports: when reimbursed (cash) or when approved (accrual)
        select coalesce(m.account_id, d_exp), case when cash then r.paid_at else i.spent_on end, 'expense', i.amount
          from expense_items i join expense_reports r on r.id = i.report_id
          left join fin_map m on m.workspace_id = w and m.source = 'expense' and m.category = i.category
         where i.workspace_id = w and (case when cash then r.status = 'Paid' else r.status in ('Approved', 'Paid') end)
        union all
        select e.account_id, e.entry_date, 'entry', e.amount from fin_entries e where e.workspace_id = w
      ) s where d between p_from and p_to and a is not null
      group by a, to_char(d, 'YYYY-MM'), src) x), '[]'),
    'budget', coalesce((select jsonb_agg(jsonb_build_object('a', b.account_id, 'm', to_char(b.month, 'YYYY-MM'), 'q', b.qty, 'v', b.amount))
                          from fin_budget b where b.workspace_id = w and b.month between date_trunc('month', p_from)::date and p_to), '[]'));
end $$;

-- receivables and reimbursements owed, as of a date (for the balance sheet)
create or replace function public.fin_balances(p_asof date) returns jsonb
language plpgsql stable security definer set search_path = public as $$
declare w uuid := ws();
begin
  if not is_admin() then raise exception 'Only admins can use Finance.'; end if;
  perform plan_require('finance');
  return jsonb_build_object(
    'receivable', coalesce((select sum(fin_inv_total(i) - case when i.status = 'Paid' and i.paid_at <= p_asof then coalesce(i.paid_amount, fin_inv_total(i)) else 0 end)
                              from inv_invoices i where i.workspace_id = w and i.status in ('Sent', 'Paid') and i.issue_date <= p_asof
                               and not (i.status = 'Paid' and i.paid_at <= p_asof and coalesce(i.paid_amount, fin_inv_total(i)) >= fin_inv_total(i))), 0),
    'sales_tax', coalesce((select sum(fin_inv_total(i) - fin_inv_net(i)) from inv_invoices i where i.workspace_id = w and i.status in ('Sent', 'Paid') and i.issue_date <= p_asof), 0),
    'reimburse', coalesce((select sum(it.amount) from expense_items it join expense_reports r on r.id = it.report_id
                             where it.workspace_id = w and r.status = 'Approved' and r.decided_at::date <= p_asof), 0));
end $$;

-- project profitability for a date range
create or replace function public.fin_projects(p_from date, p_to date) returns jsonb
language plpgsql stable security definer set search_path = public as $$
declare w uuid := ws();
begin
  if not is_admin() then raise exception 'Only admins can use Finance.'; end if;
  perform plan_require('finance');
  return coalesce((select jsonb_agg(r order by r.billed desc, r.name) from (
    select p.id, p.name, p.code, p.client, p.status, p.contract_value, p.budget_amount, p.budget_hours, p.rate,
      coalesce((select sum(fin_inv_net(i)) from inv_invoices i where i.workspace_id = w and i.project_id = p.id and i.status in ('Sent', 'Paid') and i.issue_date between p_from and p_to), 0) billed,
      coalesce((select sum(case when fin_inv_total(i) > 0 then coalesce(i.paid_amount, fin_inv_total(i)) * fin_inv_net(i) / fin_inv_total(i) else 0 end) from inv_invoices i where i.workspace_id = w and i.project_id = p.id and i.status = 'Paid' and i.paid_at between p_from and p_to), 0) collected,
      coalesce((select sum(c.amount) from project_costs c where c.project_id = p.id and c.cost_date between p_from and p_to), 0) costs,
      coalesce(h.hours, 0) hours, coalesce(h.value, 0) labor_value, coalesce(h.staff_cost, 0) staff_cost, coalesce(h.contractor_cost, 0) contractor_cost,
      coalesce((select sum(fin_inv_net(i)) from inv_invoices i where i.workspace_id = w and i.project_id = p.id and i.status in ('Sent', 'Paid')), 0) billed_all
    from projects p
    left join lateral (
      select sum(e.hours) hours, sum(e.hours * coalesce(p.rate, pp.rate, 0)) value,
             sum(case when o.kind in ('Employee', 'Intern') then e.hours * coalesce(o.rate, 0) else 0 end) staff_cost,
             sum(case when o.kind in ('Contractor', 'Consultant', 'Advisor', 'Partner') then e.hours * coalesce(o.rate, 0) else 0 end) contractor_cost
        from time_entries e
        join timesheets t on t.user_id = e.user_id and t.week_start = week_of(e.work_date) and t.status = 'Approved'
        left join project_people pp on pp.project_id = e.project_id and pp.user_id = e.user_id
        left join lateral (select x.kind, x.rate from onboardings x where x.workspace_id = w and x.user_id = e.user_id order by x.id desc limit 1) o on true
       where e.project_id = p.id and e.work_date between p_from and p_to) h on true
    where p.workspace_id = w) r), '[]');
end $$;

revoke execute on function public.fin_setup_for(uuid) from public, anon, authenticated;
revoke execute on function public.fin_setup(), public.fin_report(date, date, text), public.fin_balances(date), public.fin_projects(date, date) from public, anon;
grant execute on function public.fin_setup(), public.fin_report(date, date, text), public.fin_balances(date), public.fin_projects(date, date) to authenticated;

-- 1099-NEC summary: also count payments recorded in Finance → Transactions whose payee is the contractor (or their firm)
create or replace function public.tax_1099(p_year int) returns jsonb
language plpgsql stable security definer set search_path = public as $$
declare thr numeric := case when p_year >= 2026 then 2000 else 600 end;
begin
  if not is_admin() then raise exception 'Only admins can see the 1099 summary.'; end if;
  return jsonb_build_object('year', p_year, 'threshold', thr, 'rows', coalesce((
    select jsonb_agg(r order by r.paid desc, r.name) from (
      select o.id, o.name, o.entity, o.kind, o.firm, o.tax_form, o.tax_status, o.tax_class, o.us_person, o.status,
        coalesce(pc.v, 0) + coalesce(fe.v, 0) as paid,
        (coalesce(o.us_person, o.tax_form is distinct from 'W-8BEN' and o.tax_form is distinct from 'W-8BEN-E')
          and coalesce(o.tax_class, '') !~* 'corporation|c corp|s corp'
          and coalesce(pc.v, 0) + coalesce(fe.v, 0) >= thr) as needs_1099
      from onboardings o
      left join lateral (select sum(c.amount) v from project_costs c where c.workspace_id = o.workspace_id and extract(year from c.cost_date) = p_year
          and (c.agreement_id in (select a.id from agreements a where a.onboarding_id = o.id)
               or (c.agreement_id is null and lower(trim(c.vendor)) in (lower(trim(o.name)), lower(trim(coalesce(o.firm, ''))))))) pc on true
      left join lateral (select sum(e.amount) v from fin_entries e join fin_accounts a on a.id = e.account_id
          where e.workspace_id = o.workspace_id and extract(year from e.entry_date) = p_year and a.direction = 'out' and e.batch is null
            and lower(trim(e.payee)) in (lower(trim(o.name)), lower(trim(coalesce(o.firm, ''))))) fe on true
      where o.workspace_id = ws() and o.kind in ('Contractor', 'Consultant', 'Partner', 'Advisor', 'Intern')) r
    where r.paid > 0 or r.status in ('Planned', 'In progress', 'Active')), '[]'));
end $$;
revoke execute on function public.tax_1099(int) from public, anon;
grant execute on function public.tax_1099(int) to authenticated;
